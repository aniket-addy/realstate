const express = require("express");

const {
  getLeads,
  getLeadById,
  createLead,
  updateLead,
  updateLeadStatus,
  deleteLead,
  getLeadStats,
} = require("../controllers/leadController");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| LEAD STATS
|--------------------------------------------------------------------------
*/

router.get(
  "/stats",
  getLeadStats
);

/*
|--------------------------------------------------------------------------
| ALL LEADS
|--------------------------------------------------------------------------
*/

router.get(
  "/",
  getLeads
);

/*
|--------------------------------------------------------------------------
| CREATE LEAD
|--------------------------------------------------------------------------
*/

router.post(
  "/",
  createLead
);

/*
|--------------------------------------------------------------------------
| SINGLE LEAD
|--------------------------------------------------------------------------
*/

router.get(
  "/:id",
  getLeadById
);

/*
|--------------------------------------------------------------------------
| UPDATE COMPLETE LEAD
|--------------------------------------------------------------------------
*/

router.put(
  "/:id",
  updateLead
);

/*
|--------------------------------------------------------------------------
| UPDATE ONLY STATUS
|--------------------------------------------------------------------------
*/

router.patch(
  "/:id/status",
  updateLeadStatus
);

/*
|--------------------------------------------------------------------------
| DELETE LEAD
|--------------------------------------------------------------------------
*/

router.delete(
  "/:id",
  deleteLead
);

module.exports = router;